-- 1. Buat tabel 'orders' untuk menyimpan daftar pesanan dapur
CREATE TABLE IF NOT EXISTS public.orders (
  id           bigint generated by default as identity primary key,
  chef_id      uuid references auth.users(id) on delete set null,
  menu_name    text not null check (char_length(trim(menu_name)) >= 3),
  table_number text not null,
  notes        text default '',
  status       text not null default 'PENDING' check (status in ('PENDING', 'COOKING', 'DONE')),
  created_at   timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 2. Jika tabel sudah pernah dibuat sebelumnya dengan chef_id NOT NULL, jalankan ini:
ALTER TABLE public.orders ALTER COLUMN chef_id DROP NOT NULL;

-- 3. Nonaktifkan RLS agar data pesanan bisa langsung dibaca, ditambah, dan diubah tanpa login:
ALTER TABLE public.orders DISABLE ROW LEVEL SECURITY;

