-- 1. Buat tabel 'tasks' untuk To-Do List yang terisolasi per user
CREATE TABLE IF NOT EXISTS public.tasks (
  id           bigint generated by default as identity primary key,
  user_id      uuid default auth.uid() references auth.users(id) on delete cascade not null,
  judul        text not null check (char_length(trim(judul)) >= 1),
  isi          text not null check (char_length(trim(isi)) >= 1),
  is_completed boolean not null default false,
  created_at   timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 2. Aktifkan Row Level Security (RLS) agar tiap user hanya bisa melihat datanya sendiri
ALTER TABLE public.tasks ENABLE ROW LEVEL SECURITY;

-- 3. Policy SELECT: User hanya dapat melihat tugas miliknya
DROP POLICY IF EXISTS "User hanya melihat tasks miliknya" ON public.tasks;
CREATE POLICY "User hanya melihat tasks miliknya"
ON public.tasks FOR SELECT TO authenticated
USING (auth.uid() = user_id);

-- 4. Policy INSERT: User hanya dapat menambah tugas miliknya
DROP POLICY IF EXISTS "User hanya menambah tasks miliknya" ON public.tasks;
CREATE POLICY "User hanya menambah tasks miliknya"
ON public.tasks FOR INSERT TO authenticated
WITH CHECK (auth.uid() = user_id);

-- 5. Policy UPDATE: User hanya dapat mengubah tugas miliknya
DROP POLICY IF EXISTS "User hanya mengubah tasks miliknya" ON public.tasks;
CREATE POLICY "User hanya mengubah tasks miliknya"
ON public.tasks FOR UPDATE TO authenticated
USING (auth.uid() = user_id)
WITH CHECK (auth.uid() = user_id);

-- 6. Policy DELETE: User hanya dapat menghapus tugas miliknya
DROP POLICY IF EXISTS "User hanya menghapus tasks miliknya" ON public.tasks;
CREATE POLICY "User hanya menghapus tasks miliknya"
ON public.tasks FOR DELETE TO authenticated
USING (auth.uid() = user_id);

